const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { execFileSync } = require('node:child_process')
const vscode = require('vscode')

exports.run = async function () {
  const checks = []
  const passed = (message) => { checks.push(message); console.log(message) }
  const repo = path.join(process.env.PR_LENS_TEST_DIRECTORY, 'repository')
  fs.mkdirSync(repo)
  const git = (...args) => execFileSync('git', args, { cwd: repo, encoding: 'utf8' }).trim()
  git('init', '-q', '-b', 'main')
  git('config', 'user.name', 'Test')
  git('config', 'user.email', 'test@example.invalid')
  git('config', 'commit.gpgsign', 'false')
  const commit = (message) => {
    git('add', '.')
    git('commit', '-q', '--allow-empty', '-m', message)
    return git('rev-parse', 'HEAD')
  }
  fs.writeFileSync(path.join(repo, 'file name #1.txt'), 'before\n')
  const root = commit('Initial commit')
  for (let i = 0; i < 104; i++) commit(`Inherited ${i}`)
  git('checkout', '-q', '-b', 'feature')
  fs.writeFileSync(path.join(repo, 'file name #1.txt'), 'after\n')
  const first = commit('Feature one')
  fs.writeFileSync(path.join(repo, 'second.txt'), 'second\n')
  const second = commit('Feature two')
  fs.writeFileSync(path.join(repo, 'file name #1.txt'), 'uncommitted\n')

  const extension = vscode.extensions.getExtension('rmegi.pr-lens')
  assert.ok(extension)
  const api = await extension.activate()
  const command = async (name, ...args) => {
    await vscode.commands.executeCommand(`prLens.${name}`, ...args)
    assert.equal(api.error, '', `Command ${name}: ${api.error}`)
  }
  await command('openRepository', vscode.Uri.file(repo))
  assert.equal(api.base, 'main')
  assert.equal(api.head, 'feature')
  assert.deepEqual(api.commits.map((c) => c.hash), [second, first])
  assert.equal(api.hasMore, false)
  assert.equal(api.comparison.files.length, 2)
  passed('PASS: repository discovery, default branches, feature-only history')

  const group = (id) => api.getChildren().find((item) => item.id === id)
  const firstFile = api.getChildren(group('files')).find((item) => item.label === 'file name #1.txt')
  await vscode.commands.executeCommand(firstFile.command.command, ...firstFile.command.arguments)
  const original = vscode.workspace.textDocuments.find((d) => d.uri.scheme === 'pr-lens' && JSON.parse(d.uri.query).side === 'original')
  const modified = vscode.workspace.textDocuments.find((d) => d.uri.scheme === 'pr-lens' && JSON.parse(d.uri.query).side === 'modified')
  assert.equal(original.getText(), 'before\n')
  assert.equal(modified.getText(), 'after\n')
  assert.equal(JSON.parse(modified.uri.query).head, second)
  assert.ok(vscode.window.tabGroups.all.some((g) => g.tabs.some((t) => t.input instanceof vscode.TabInputTextDiff)))
  fs.writeFileSync(path.join(repo, 'new.txt'), 'new\n')
  commit('Branch advances')
  assert.equal((await vscode.workspace.openTextDocument(modified.uri)).getText(), 'after\n')
  passed('PASS: native diff, special-character filenames, immutable historical documents')

  await command('showCommit', first)
  assert.equal(api.commit.hash, first)
  assert.equal(api.comparison.files.length, 1)
  assert.equal(api.getChildren(group('commits')).length, 2)
  assert.equal(api.getChildren(group('commits')).find((i) => i.id === `commit:${first}`).iconPath.id, 'check')
  assert.ok(api.getChildren().some((i) => i.id === 'back'))
  await command('showBranchComparison')
  assert.equal(api.commit, undefined)
  assert.ok(!api.getChildren().some((i) => i.id === 'back'))
  passed('PASS: select commit, preserve history, return to branch comparison')

  await command('selectHistory', 'main')
  assert.equal(api.commits.length, 100)
  assert.equal(api.hasMore, true)
  await command('loadMore')
  assert.equal(api.commits.length, 105)
  assert.equal(api.hasMore, false)
  await command('selectHistory', 'feature')
  assert.equal(api.commits.length, 3)
  assert.equal(api.head, 'feature')
  assert.equal(api.base, 'main')
  await command('selectHead', 'main')
  assert.equal(api.comparison.files.length, 0)
  await command('selectHead', 'feature')
  assert.equal(api.commits.length, 3)
  await Promise.all([command('selectHistory', 'main'), command('selectHistory', 'feature')])
  assert.equal(api.historyBranch, 'feature')
  assert.equal(api.commits.length, 3)
  passed('PASS: history paging, branch switching, comparison selection, rapid switches')

  await command('showCommit', root)
  assert.equal(api.comparison.base, 'Empty tree')
  assert.equal(api.comparison.files[0].status, 'A')
  const rootOriginal = vscode.workspace.textDocuments.find((d) => d.uri.scheme === 'pr-lens' && JSON.parse(d.uri.query).head === root && JSON.parse(d.uri.query).side === 'original')
  assert.equal(rootOriginal.getText(), '')
  const invalid = vscode.Uri.from({ scheme: 'pr-lens', path: '/test.txt', query: JSON.stringify({ repo, side: 'unknown' }) })
  await assert.rejects(vscode.workspace.openTextDocument(invalid))
  passed('PASS: root commit and document input validation')

  const current = git('rev-parse', 'HEAD')
  fs.writeFileSync(path.join(repo, 'second.txt'), 'dirty\n')
  const status = git('status', '--porcelain')
  await command('refresh')
  assert.equal(git('rev-parse', 'HEAD'), current)
  assert.equal(git('symbolic-ref', '--short', 'HEAD'), 'feature')
  assert.equal(git('status', '--porcelain'), status)
  assert.equal(fs.readFileSync(path.join(repo, 'second.txt'), 'utf8'), 'dirty\n')
  passed('PASS: browsing leaves the working tree unchanged')
  const chatChecks = await require('./chat.test.cjs').run({ api, repo, first, second, root })
  for (const check of chatChecks) passed(check)
  await vscode.commands.executeCommand('workbench.action.closeAllEditors')
  fs.writeFileSync(path.join(process.env.PR_LENS_TEST_DIRECTORY, 'results.json'), JSON.stringify(checks))
}
